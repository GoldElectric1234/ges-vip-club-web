// Translation function
export const t = (key: string, language: Language = 'en'): string => {
  return translations[language][key] ?? translations.en[key] ?? key;
};

// Get default language from localStorage or system
export const getDefaultLanguage = (): Language => {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('ges-language');
    if (stored === 'en' || stored === 'es') {
      return stored;
    }
  }
  return 'en';
};

// Save language preference
export const saveLanguagePreference = (language: Language) => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('ges-language', language);
  }
};
